#!/usr/bin/env node
// Generates the configurator "frames" the vendored gatekeepers import.
//
// Upstream (cloudflare-os) compiles each gatekeeper's configurator spec
// (src/configurator/<name>-configurator-ui.tsx) into a sandboxed iframe document,
// src/generated/<name>-configurator-ui.txt, which `startResourceConfigurator()` returns as
// `iframeHtml`. We don't vendor that runtime: the CRM app renders the specs natively with its own
// components (apps/app/src/components/integrations/configurator) and only uses the `ui` capability
// `startResourceConfigurator()` returns. The vendored sources still import the frames, so this
// writes a tiny document for each one they import. The files are build outputs, ignored by git.
//
//   node scripts/gatekeeper-configurator-frames.mjs          writes every frame the sources import
//   node scripts/gatekeeper-configurator-frames.mjs --check  fails if git tracks any frame, or
//                                                            would not ignore one
//
// Run from anywhere; the package scripts run it before typecheck, test and build.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packagesDir = join(root, "packages");
const FRAME_IMPORT = /["'](\.{1,2}\/(?:[\w-]+\/)*generated\/([\w-]+)-configurator-ui\.txt)["']/g;

/** Every `.ts` file under `dir`, skipping generated output and dependencies. */
function sources(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return entry.name === "generated" || entry.name === "node_modules" ? [] : sources(path);
    }
    return /\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [path] : [];
  });
}

/** The frames the gatekeepers import: file path -> `<vendor>/<name>`. */
function frames() {
  const found = new Map();
  for (const entry of readdirSync(packagesDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || !entry.name.startsWith("gatekeeper-")) continue;
    const vendor = entry.name.slice("gatekeeper-".length);
    let files;
    try {
      files = sources(join(packagesDir, entry.name, "src"));
    } catch {
      continue;
    }
    for (const file of files) {
      for (const match of readFileSync(file, "utf8").matchAll(FRAME_IMPORT)) {
        found.set(join(dirname(file), match[1]), `${vendor}/${match[2]}`);
      }
    }
  }
  return found;
}

function frameHtml(spec) {
  const [vendor, name] = spec.split("/");
  return `<!doctype html>
<!--
  Generated by scripts/gatekeeper-configurator-frames.mjs: do not edit or commit (git ignores it).
  The CRM renders this configurator natively from
  packages/gatekeeper-${vendor}/src/configurator/${name}-configurator-ui.tsx with its own components
  (apps/app/src/components/integrations/configurator); it uses only the \`ui\` capability that
  startResourceConfigurator() returns beside this document.
-->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="crm-configurator" content="${spec}" />
    <title>Configurator rendered by the CRM</title>
  </head>
  <body>
    <p>This configurator (${spec}) is rendered natively by the CRM app.</p>
  </body>
</html>
`;
}

function git(args) {
  return execFileSync("git", args, {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
}

function check() {
  try {
    git(["rev-parse", "--is-inside-work-tree"]);
  } catch {
    console.log("gatekeeper-configurator-frames: not a git checkout, nothing to check");
    return;
  }
  const paths = [...frames().keys()].map((path) => relative(root, path));
  const tracked = git([
    "ls-files",
    "--",
    "packages/gatekeeper-*/src/generated/*-configurator-ui.txt",
  ])
    .split("\n")
    .filter(Boolean);
  let ignored = [];
  try {
    ignored = git(["check-ignore", "--no-index", ...paths])
      .split("\n")
      .filter(Boolean);
  } catch {
    // check-ignore exits 1 when it ignores none of them.
  }
  const unignored = paths.filter((path) => !ignored.includes(path));
  if (tracked.length > 0 || unignored.length > 0) {
    if (tracked.length > 0) {
      console.error(
        "gatekeeper-configurator-frames: these generated frames are tracked by git; remove them " +
          `from the index (git rm --cached):\n  ${tracked.join("\n  ")}`,
      );
    }
    if (unignored.length > 0) {
      console.error(
        `gatekeeper-configurator-frames: .gitignore does not ignore:\n  ${unignored.join("\n  ")}`,
      );
    }
    process.exit(1);
  }
  console.log(`gatekeeper-configurator-frames: ${paths.length} frames, none tracked`);
}

function generate() {
  let written = 0;
  const all = frames();
  for (const [path, spec] of all) {
    const html = frameHtml(spec);
    let current;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = undefined;
    }
    if (current === html) continue;
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, html);
    written++;
  }
  if (written > 0) console.log(`gatekeeper-configurator-frames: wrote ${written} of ${all.size}`);
}

if (process.argv.includes("--check")) check();
else generate();
