#!/usr/bin/env node
// Runs `wrangler types` for a vendored gatekeeper Worker and post-processes the output the way
// cloudflare-os does (adapted from its scripts/generate-worker-types.ts, Apache-2.0):
//
// - The Worker's `main` is the capnweb-validate output under .wrangler/validate, so the generated
//   `mainModule` is pointed back at the source file it was built from.
// - A package whose src/env.d.ts declares `GlobalProps` itself gets runtime types only.
// - `restore` is declared on `cloudflare:workers`: the runtime exports it but its types do not yet.
//
//   node ../../scripts/gatekeeper-worker-types.mjs          (from a package dir) writes the file
//   node ../../scripts/gatekeeper-worker-types.mjs --check  fails if it is out of date
import { spawnSync } from "node:child_process";
import { readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

const pkgDir = process.cwd();
const check = process.argv.includes("--check");
const typesPath = join(pkgDir, "worker-configuration.d.ts");
const outPath = check ? join(pkgDir, "worker-configuration.check.d.ts") : typesPath;

const RESTORE_PATCH = `

    // TODO: Fix bug in runtime types where this isn't declared in the types. It is actually
    // exported by the runtime.
    export const restore: symbol;
`;

async function ownsGlobalProps() {
  try {
    const text = await readFile(join(pkgDir, "src", "env.d.ts"), "utf8");
    return /\binterface\s+GlobalProps\b/.test(text);
  } catch {
    return false;
  }
}

function rewriteMainModule(text) {
  return text.replace(
    /mainModule:\s*typeof import\("\.\/\.wrangler\/validate\/src\/([^"]+)"\)/g,
    'mainModule: typeof import("./src/$1")',
  );
}

function stripProjectHeader(text) {
  const begin = text.indexOf("// Begin runtime types");
  if (begin < 0) return text;
  const workerd =
    text.match(/\/\/ Runtime types generated with workerd@[^\n]+/)?.[0] ??
    "// Runtime types generated with workerd";
  return `/* eslint-disable */\n${workerd}\n${text.slice(begin)}`;
}

function ensureRestoreExport(text) {
  if (/export const restore: symbol;/.test(text)) return text;
  const marker = /export const tracing: Tracing;\n\}/;
  if (!marker.test(text)) {
    throw new Error("could not find the cloudflare:workers module types to patch `restore` into");
  }
  return text.replace(marker, `export const tracing: Tracing;${RESTORE_PATCH}}`);
}

function normalizeBanner(text) {
  return text.replace(
    /^\/\/ Generated by Wrangler by running `wrangler types[^`]*`/m,
    "// Generated by Wrangler by running `wrangler types`",
  );
}

const result = spawnSync("pnpm", ["exec", "wrangler", "types", outPath, "--strict-vars=false"], {
  cwd: pkgDir,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "pipe"],
});
if (result.status !== 0) {
  console.error(result.stdout, result.stderr);
  process.exit(result.status ?? 1);
}

let text = normalizeBanner(await readFile(outPath, "utf8"));
text = rewriteMainModule(text);
if (await ownsGlobalProps()) text = stripProjectHeader(text);
text = ensureRestoreExport(text).replace(/[ \t]+$/gm, "");

if (check) {
  await rm(outPath);
  const current = await readFile(typesPath, "utf8").catch(() => "");
  if (current !== text) {
    console.error("worker-configuration.d.ts is out of date: run `pnpm types` in this package.");
    process.exit(1);
  }
} else {
  await writeFile(typesPath, text);
}
