// The automation page's Overview tab, in the reference design's layout
// (docs/stages/assets/05-automation-page.html): a two-column grid (1fr / 360px, one column under
// 900px). Left: What it does, Steps, Test mode. Right: Permissions (approved), Safety rails,
// Recent runs.
import type { AutomationTestReport } from "@relationship-os/core";
import { Badge } from "@relationship-os/ui/components/badge";
import { Button } from "@relationship-os/ui/components/button";
import { Skeleton } from "@relationship-os/ui/components/skeleton";
import { cn } from "@relationship-os/ui/lib/utils";
import { Link } from "@tanstack/react-router";
import { SparklesIcon } from "lucide-react";
import { Fragment, useState } from "react";
import { useStageMutation } from "#/lib/automation-ops";
import { errorMessage } from "#/lib/query";
import { useObjectInfo } from "#/lib/schema";
import { type AutomationDetailData, useRuns } from "./hooks.ts";
import { compactRelative, diagramParts } from "./model.ts";
import { InfoCard, RunOutcome, TestReportView } from "./parts.tsx";

type DiagramNode = AutomationDetailData["diagram"][number];

const NODE_STYLE: Record<DiagramNode["kind"], string> = {
  trigger: "border-indigo-300 bg-indigo-50 dark:border-indigo-400/40 dark:bg-indigo-500/10",
  condition: "border-amber-300 bg-amber-50 dark:border-amber-400/40 dark:bg-amber-500/10",
  do: "bg-background",
  notify: "bg-background",
  sleep: "border-dashed bg-background",
  waitForEvent: "border-dashed bg-background",
};

export function OverviewTab({
  detail,
  report,
  onOpenRuns,
}: {
  detail: AutomationDetailData;
  /** The latest test report: this session's, else the stored one. */
  report: AutomationTestReport | null;
  onOpenRuns: (runId?: string) => void;
}) {
  return (
    <div
      className="grid grid-cols-1 items-start gap-4 min-[900px]:grid-cols-[minmax(0,1fr)_360px]"
      data-testid="automation-overview"
    >
      <div className="grid min-w-0 gap-3">
        <SummaryCard detail={detail} />
        <StepsCard nodes={detail.diagram} />
        <TestCard report={report} />
      </div>
      <div className="grid min-w-0 gap-3">
        <PermissionsCard detail={detail} />
        <RailsCard rails={detail.rails} />
        <RecentRunsCard detail={detail} onOpenRuns={onOpenRuns} />
      </div>
    </div>
  );
}

function SummaryCard({ detail }: { detail: AutomationDetailData }) {
  const explain = useStageMutation("automation.explain");
  const [shown, setShown] = useState(false);
  return (
    <InfoCard title="What it does" name="plain english summary">
      <p className="text-[15px] leading-relaxed" data-testid="automation-summary">
        {detail.summary.segments.map((segment, i) =>
          segment.strong ? (
            // biome-ignore lint/suspicious/noArrayIndexKey: segments of one fixed summary
            <b key={i} className="rounded bg-muted px-1 font-medium">
              {segment.text}
            </b>
          ) : (
            // biome-ignore lint/suspicious/noArrayIndexKey: segments of one fixed summary
            <Fragment key={i}>{segment.text}</Fragment>
          ),
        )}
      </p>
      <p className="mt-2 text-sm text-muted-foreground">
        Generated by the host from the automation's declared trigger, conditions and steps, not from
        AI.{" "}
        <button
          type="button"
          className="text-foreground underline underline-offset-2 hover:no-underline"
          onClick={() => {
            if (shown) return setShown(false);
            setShown(true);
            if (!explain.data && !explain.isPending) explain.mutate({ id: detail.id });
          }}
          aria-expanded={shown}
        >
          {shown ? "Hide AI explanation" : "Show AI explanation"}
        </button>
      </p>
      {shown && (
        <div
          className="mt-3 grid gap-1.5 rounded-lg border border-dashed p-3 text-sm"
          data-testid="ai-explanation"
        >
          <Badge variant="outline" className="w-fit">
            <SparklesIcon aria-hidden />
            AI-written
          </Badge>
          {explain.isPending ? (
            <Skeleton className="h-10" />
          ) : explain.error ? (
            <span className="text-destructive">{errorMessage(explain.error)}</span>
          ) : explain.data?.text ? (
            <p className="whitespace-pre-line">{explain.data.text}</p>
          ) : (
            <span className="text-muted-foreground">No AI model is available to explain it.</span>
          )}
          {explain.data?.model && (
            <span className="text-xs text-muted-foreground">Model role: {explain.data.model}</span>
          )}
        </div>
      )}
    </InfoCard>
  );
}

function StepsCard({ nodes }: { nodes: readonly DiagramNode[] }) {
  return (
    <InfoCard title="Steps" name="step diagram">
      <ol className="flex flex-col items-center" aria-label="Steps" data-testid="step-diagram">
        {nodes.map((node, i) => (
          // biome-ignore lint/suspicious/noArrayIndexKey: the diagram is a fixed ordered list
          <li key={i} className="flex w-full flex-col items-center">
            {i > 0 && <div className="h-[18px] w-0.5 bg-border" aria-hidden />}
            <div
              className={cn(
                "w-full max-w-[440px] rounded-lg border px-3 py-2.5 text-sm",
                NODE_STYLE[node.kind],
              )}
              data-kind={node.kind}
              data-testid="diagram-node"
            >
              <div className="text-[11px] tracking-wide text-muted-foreground uppercase">
                {node.heading}
              </div>
              <div className="break-words">
                {diagramParts(node.text, node.code).map((part, j) =>
                  part.code ? (
                    // biome-ignore lint/suspicious/noArrayIndexKey: parts of one fixed node
                    <code key={j} className="rounded bg-muted px-1 py-px font-mono text-xs">
                      {part.text}
                    </code>
                  ) : (
                    // biome-ignore lint/suspicious/noArrayIndexKey: parts of one fixed node
                    <Fragment key={j}>{part.text}</Fragment>
                  ),
                )}
                {node.detail && <span className="text-muted-foreground"> {node.detail}</span>}
                {node.risk && (
                  <span className="ml-1.5 inline-block rounded bg-amber-100 px-1.5 py-px text-[11px] text-amber-900 dark:bg-amber-500/15 dark:text-amber-300">
                    {node.risk}
                  </span>
                )}
              </div>
            </div>
          </li>
        ))}
      </ol>
    </InfoCard>
  );
}

function TestCard({ report }: { report: AutomationTestReport | null }) {
  const title = report
    ? report.record?.title
      ? `Test mode · last run against “${report.record.title}”`
      : "Test mode · last run"
    : "Test mode";
  return (
    <InfoCard title={title} name="test mode result">
      {report ? (
        <TestReportView report={report} />
      ) : (
        <p className="rounded-lg bg-muted/60 p-3 text-sm text-muted-foreground">
          Not tested yet. “Test on a record…” shows exactly what it would do, with nothing written.
        </p>
      )}
    </InfoCard>
  );
}

function PermissionsCard({ detail }: { detail: AutomationDetailData }) {
  const { permissions } = detail;
  const join = (items: readonly string[]) => items.join(", ") || "nothing";
  return (
    <InfoCard title="Permissions (approved)" name="permissions">
      <div className="grid gap-0.5 text-sm">
        <div>Read: {join(permissions.read)}</div>
        <div>Write: {join(permissions.write)}</div>
        {permissions.notify && <div>Notify: users</div>}
        {permissions.operations.length > 0 && (
          <div className="break-words">Operations: {permissions.operations.join(", ")}</div>
        )}
      </div>
      <div className="mt-1.5 text-sm text-muted-foreground">
        Runs as{" "}
        <code className="rounded bg-muted px-1 font-mono text-xs">{permissions.principal}</code> ·
        actor <code className="rounded bg-muted px-1 font-mono text-xs">automation</code>
      </div>
    </InfoCard>
  );
}

function RailsCard({ rails }: { rails: AutomationDetailData["rails"] }) {
  return (
    <InfoCard title="Safety rails" name="safety">
      <div className="grid gap-0.5 text-sm">
        <div>
          Max {rails.maxRunsPerMinute} runs/min · {rails.maxWritesPerHour} writes/hour
        </div>
        <div>Cascade depth {rails.cascadeDepth} · no self-retrigger</div>
        <div className="text-muted-foreground">Auto-pauses and notifies admins if exceeded</div>
      </div>
    </InfoCard>
  );
}

function RecentRunsCard({
  detail,
  onOpenRuns,
}: {
  detail: AutomationDetailData;
  onOpenRuns: (runId?: string) => void;
}) {
  const { query, items } = useRuns({ id: detail.id, limit: 5 });
  const { object } = useObjectInfo(detail.triggerObject ?? "");
  const runs = items.slice(0, 5);
  return (
    <InfoCard
      title="Recent runs"
      name="recent runs"
      action={
        detail.runCount > 0 ? (
          <Button
            variant="link"
            size="sm"
            className="h-auto p-0 text-xs"
            onClick={() => onOpenRuns()}
          >
            All runs
          </Button>
        ) : undefined
      }
    >
      {query.isPending ? (
        <Skeleton className="h-24" />
      ) : query.error ? (
        <p className="text-sm text-destructive">{errorMessage(query.error)}</p>
      ) : !runs.length ? (
        <p className="text-sm text-muted-foreground">No runs yet.</p>
      ) : (
        <table className="w-full text-sm" data-testid="recent-runs">
          <thead>
            <tr className="border-b text-left text-muted-foreground">
              <th className="px-1 py-1.5 font-medium">{object?.label ?? "Record"}</th>
              <th className="px-1 py-1.5 font-medium">When</th>
              <th className="px-1 py-1.5 font-medium">Outcome</th>
            </tr>
          </thead>
          <tbody>
            {runs.map((run) => (
              <tr key={run.id} className="border-b last:border-0">
                <td className="max-w-32 truncate px-1 py-1.5">
                  <button
                    type="button"
                    className="max-w-full truncate text-left hover:underline"
                    onClick={() => onOpenRuns(run.id)}
                  >
                    {run.record?.title ?? (run.record ? run.record.id : "Scheduled")}
                  </button>
                </td>
                <td className="px-1 py-1.5 whitespace-nowrap text-muted-foreground">
                  {compactRelative(run.startedAt)}
                </td>
                <td className="px-1 py-1.5">
                  <RunOutcome run={run} />
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
      {detail.killSwitch && (
        <p className="mt-2 text-xs text-muted-foreground">
          The kill switch is on: no runs start.{" "}
          <Link to="/settings/automations" className="underline">
            Settings
          </Link>
        </p>
      )}
    </InfoCard>
  );
}
